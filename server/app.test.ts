import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import request from 'supertest';
import { createApp } from './app.js';

test('Persistent learning, anti-farm XP, source import and verified backup restore', async () => {
  const dir=mkdtempSync(path.join(tmpdir(),'academy-api-'));
  const catalog=path.join(dir,'catalog.json');
  writeFileSync(catalog,JSON.stringify({documents:[],lessons:[{id:'caesar',courseId:'security',moduleId:'classical',content:{},title:'Caesar',summary:'Test',exercises:[{id:'ex-1',type:'text',prompt:'A + 3?',answer:'D',explanation:'A dịch 3 vị trí thành D.',supplemental:true},{id:'ex-2',type:'text',prompt:'B + 3?',answer:'E',explanation:'B dịch 3 vị trí thành E.',supplemental:true}]}]}));
  let instance=createApp({dataDir:dir,catalogPath:catalog});
  try {
    let api=request(instance.app);
    const boot=await api.get('/api/bootstrap').expect(200);
    assert.equal(boot.body.stats.xp,0);
    assert.equal(boot.body.progress[0].completed,false);
    assert.equal(typeof boot.body.capabilities.cppRunner,'boolean');
    const lesson=await api.get('/api/lessons/caesar').expect(200);
    assert.equal(lesson.body.exercises[0].answer,undefined);
    const wrong=await api.post('/api/submissions').send({exerciseId:'ex-1',answer:'C'}).expect(200);
    assert.equal(wrong.body.correct,false);
    const right=await api.post('/api/submissions').send({exerciseId:'ex-1',answer:'d'}).expect(200);
    assert.equal(right.body.correct,true);
    assert.equal(right.body.xp,25);
    const repeated=await api.post('/api/submissions').send({exerciseId:'ex-1',answer:'D'}).expect(200);
    assert.equal(repeated.body.xp,0);
    await api.post('/api/submissions').send({exerciseId:'ex-2',answer:'E'}).expect(200);
    const mastered=await api.get('/api/bootstrap').expect(200);
    assert.equal(mastered.body.progress[0].completed,true);
    assert.equal(mastered.body.stats.xp,50);
    assert.equal(mastered.body.reviews.length,1);
    assert.ok(mastered.body.achievements.find((a:any)=>a.id==='comeback').earnedAt);
    await api.post(`/api/reviews/${mastered.body.reviews[0].id}`).send({answer:'D'}).expect(400);
    instance.db.prepare('UPDATE review_schedule SET due_at=? WHERE id=?').run('2000-01-01T00:00:00.000Z',mastered.body.reviews[0].id);
    const reviewed=await api.post(`/api/reviews/${mastered.body.reviews[0].id}`).send({answer:'D'}).expect(200);
    assert.equal(reviewed.body.correct,true);
    assert.equal(reviewed.body.xp,10);
    assert.equal(reviewed.body.reviews[0].intervalDays,3);
    await api.post(`/api/reviews/${mastered.body.reviews[0].id}`).send({answer:'D'}).expect(400);
    await api.put('/api/code/caesar').send({code:'int main() {}'}).expect(200);
    const course=await api.post('/api/courses').send({title:'Lập trình',description:'C++ cơ bản'}).expect(201);
    const module=await api.post('/api/modules').send({courseId:course.body.id,title:'Vòng cơ bản'}).expect(201);
    const authored=await api.post('/api/lessons').send({courseId:course.body.id,moduleId:module.body.id,title:'Cộng hai số',summary:'Bài do người dùng biên soạn',content:{stages:[{title:'Khởi động',body:'Tính 2+3.'}]},exercises:[{id:'new-exercise',prompt:'2+3 = ?',answer:'5',explanation:'Cộng hai số.',supplemental:true}],sourceReferences:[],confirmed:true}).expect(201);
    assert.equal(authored.body.lesson.content.editorialStatus,'manually-reviewed');
    await api.post('/api/lessons').send({courseId:course.body.id,moduleId:module.body.id,title:'Sai nguồn',content:{},sourceReferences:['made-up'],confirmed:true}).expect(400);
    const text=Buffer.from('Tài liệu thật\n\nĐoạn hai.');
    const imported=await api.post('/api/documents').set('Content-Type','application/octet-stream').set('x-file-name',encodeURIComponent('bai-hoc.txt')).set('x-course-id',course.body.id).send(text).expect(201);
    const doc=imported.body.document;
    assert.equal(doc.status,'review');
    assert.equal(doc.referenceCount,2);
    const found=await api.get('/api/search').query({q:'Đoạn hai'}).expect(200);
    assert.equal(found.body.documents[0].id,doc.id);
    const none=await api.get('/api/search').query({q:'%wildcard%'}).expect(200);
    assert.equal(none.body.documents.length,0);
    const duplicate=await api.post('/api/documents').set('Content-Type','application/octet-stream').set('x-file-name','duplicate.txt').send(text).expect(200);
    assert.equal(duplicate.body.duplicate,true);
    assert.equal(duplicate.body.document.id,doc.id);
    await api.post(`/api/documents/${doc.id}/publish`).send({confirmed:true}).expect(200);
    const original=await api.get(`/api/documents/${doc.id}/file`).expect(200);
    assert.equal(original.text,text.toString());
    await api.post('/api/documents').set('Content-Type','application/octet-stream').set('x-file-name','bad.ppt').send(Buffer.from('not office')).expect(400);
    await api.post('/api/documents').set('Content-Type','application/octet-stream').set('x-file-name',encodeURIComponent('../bad.txt')).send(text).expect(400);
    await api.post('/api/courses').set('Origin','https://untrusted.example').send({title:'No'}).expect(403);
    const backup=(await api.get('/api/backup').expect(200)).body;
    const corrupted=structuredClone(backup);corrupted.payload.tables.courses[0].title='tampered';
    await api.post('/api/restore').send({confirm:true,backup:corrupted}).expect(400);
    await api.post('/api/restore').send({confirm:false,backup}).expect(400);
    await api.post('/api/courses').send({title:'Created after backup'}).expect(201);
    await api.post('/api/restore').send({confirm:true,backup}).expect(200);
    assert.equal((await api.get('/api/bootstrap')).body.courses.some((c:any)=>c.title==='Created after backup'),false);
    instance.close();
    instance=createApp({dataDir:dir,catalogPath:catalog});api=request(instance.app);
    assert.equal((await api.get('/api/code/caesar').expect(200)).body.code,'int main() {}');
    assert.equal((await api.get('/api/bootstrap').expect(200)).body.stats.xp,60);
    await api.delete(`/api/documents/${doc.id}`).send({confirm:false}).expect(400);
    await api.delete(`/api/documents/${doc.id}`).send({confirm:true}).expect(200);
    await api.get(`/api/documents/${doc.id}`).expect(404);
  } finally {
    instance.close();
    assert.ok(path.resolve(dir).startsWith(path.resolve(tmpdir())+path.sep));
    assert.ok(path.basename(dir).startsWith('academy-api-'));
    rmSync(dir,{recursive:true,force:true});
  }
});
